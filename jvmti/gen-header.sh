# Generates C header with the TetragonHook class file bytes.
# usage: gen-header.sh <TetragonHook.class>

set -e

echo "/* SPDX-License-Identifier: Apache-2.0 */"
echo "/* Copyright Authors of Tetragon */"
echo
echo "/* Generated by gen-header.sh from TetragonHook.java, do not edit. */"
echo
echo "static const unsigned char tetragon_hook_class[] = {"
od -An -v -tx1 "$1" | sed -e 's/^ */\t/' -e 's/ *$//' -e 's/ /, /g' -e 's/\([0-9a-f][0-9a-f]\)/0x\1/g' -e 's/$/,/'
echo "};"
